CREATE TABLE IF NOT EXISTS public.portal_resource_departments (
    resource_id BIGINT NOT NULL REFERENCES public.portal_resources(id) ON DELETE CASCADE,
    department_id BIGINT NOT NULL REFERENCES public.portal_departments(id) ON DELETE CASCADE,
    PRIMARY KEY (resource_id, department_id)
);

CREATE INDEX IF NOT EXISTS portal_resource_departments_department_id
    ON public.portal_resource_departments (department_id);

INSERT INTO public.portal_resource_departments (resource_id, department_id)
SELECT resource.id, department.id
FROM public.portal_resources AS resource
CROSS JOIN public.portal_departments AS department
JOIN public.portal_faculties AS faculty ON faculty.id = department.faculty_id
JOIN public.portal_universities AS university ON university.id = faculty.university_id
WHERE UPPER(department.name) = 'BST'
  AND LOWER(faculty.name) = 'engineering technology'
  AND university.is_uovt = TRUE
  AND resource.visible_to_all_departments = FALSE
  AND NOT EXISTS (
      SELECT 1 FROM public.portal_resource_departments AS existing_access
      WHERE existing_access.resource_id = resource.id
  )
ON CONFLICT DO NOTHING;

DO $$
DECLARE
    target_department_id BIGINT;
    target_faculty_id BIGINT;
    target_university_id BIGINT;
    target_department_name TEXT;
    target_faculty_name TEXT;
    target_university_name TEXT;
    source_department RECORD;
BEGIN
    SELECT department.id, department.name, faculty.id, faculty.name, university.id, university.name
    INTO target_department_id, target_department_name, target_faculty_id, target_faculty_name,
         target_university_id, target_university_name
    FROM public.portal_departments AS department
    JOIN public.portal_faculties AS faculty ON faculty.id = department.faculty_id
    JOIN public.portal_universities AS university ON university.id = faculty.university_id
    WHERE university.is_uovt = TRUE
      AND LOWER(faculty.name) = 'engineering technology'
      AND LOWER(REGEXP_REPLACE(BTRIM(department.name), '[[:space:]]+', ' ', 'g')) = 'bst'
    ORDER BY department.active DESC, department.id
    LIMIT 1;

    IF target_department_id IS NULL THEN
        RAISE EXCEPTION 'The UoVT BST department under Engineering Technology could not be created.';
    END IF;

    FOR source_department IN
        SELECT department.id, faculty.id AS faculty_id
        FROM public.portal_departments AS department
        JOIN public.portal_faculties AS faculty ON faculty.id = department.faculty_id
        JOIN public.portal_universities AS university ON university.id = faculty.university_id
        WHERE university.is_uovt = TRUE
          AND LOWER(REGEXP_REPLACE(BTRIM(department.name), '[[:space:]]+', ' ', 'g')) = 'bst'
          AND faculty.id <> target_faculty_id
    LOOP
        UPDATE public.portal_users
        SET department_id = target_department_id,
            department = target_department_name,
            faculty = target_faculty_name,
            university_id = target_university_id,
            university_name = target_university_name
        WHERE department_id = source_department.id;

        INSERT INTO public.portal_resource_departments (resource_id, department_id)
        SELECT access.resource_id, target_department_id
        FROM public.portal_resource_departments AS access
        WHERE access.department_id = source_department.id
        ON CONFLICT DO NOTHING;

        DELETE FROM public.portal_resource_departments
        WHERE department_id = source_department.id;

        UPDATE public.portal_organization_requests
        SET resolved_department_id = target_department_id,
            resolved_faculty_id = target_faculty_id,
            resolved_university_id = target_university_id
        WHERE resolved_department_id = source_department.id;

        DELETE FROM public.portal_departments
        WHERE id = source_department.id;
    END LOOP;

    UPDATE public.portal_faculties AS faculty
    SET active = FALSE
    FROM public.portal_universities AS university
    WHERE faculty.university_id = university.id
      AND university.is_uovt = TRUE
      AND LOWER(faculty.name) = 'bst'
      AND NOT EXISTS (
          SELECT 1
          FROM public.portal_departments AS department
          WHERE department.faculty_id = faculty.id
      );
END
$$;

