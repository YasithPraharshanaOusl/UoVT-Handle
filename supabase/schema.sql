CREATE TABLE IF NOT EXISTS public.portal_organization_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    university_name TEXT NOT NULL,
    faculty_name TEXT NOT NULL,
    department_name TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
    resolved_university_id BIGINT,
    resolved_faculty_id BIGINT,
    resolved_department_id BIGINT,
    submitted_by TEXT NOT NULL,
    reviewed_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS portal_organization_requests_pending_unique
    ON public.portal_organization_requests (
        LOWER(REGEXP_REPLACE(BTRIM(university_name), '[[:space:]]+', ' ', 'g')),
        LOWER(REGEXP_REPLACE(BTRIM(faculty_name), '[[:space:]]+', ' ', 'g')),
        LOWER(REGEXP_REPLACE(BTRIM(department_name), '[[:space:]]+', ' ', 'g'))
    )
    WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS portal_organization_requests_status_created
    ON public.portal_organization_requests (status, created_at);

